// Operators in JS

let a = 10;
let b = 5;

// Arithmetic Operators
console.log("Addition:", a + b);
console.log("Subtraction:", a - b);
console.log("Multiplication:", a * b);
console.log("Division:", a / b);
console.log("Modulus:", a % b);
console.log("Exponentiation:", a ** b);

// Comparison Operators
console.log("Equal to:", a == b);
console.log("Not equal to:", a != b);
console.log("Strict equal to:", a === b);
console.log("Strict not equal to:", a !== b);
console.log("Greater than:", a > b);
console.log("Less than:", a < b);
console.log("Greater than or equal to:", a >= b);
console.log("Less than or equal to:", a <= b);

// Logical Operators
let isTrue = true;
let isFalse = false;

console.log("AND:", isTrue && isFalse);
console.log("OR:", isTrue || isFalse);
console.log("NOT:", !isTrue);

// Assignment Operators
let c = 10;
console.log("Initial value of c:", c);
c += 5; // c = c + 5
console.log("After += 5:", c);
c -= 3; // c = c - 3
console.log("After -= 3:", c);
c *= 2; // c = c * 2
console.log("After *= 2:", c);
c /= 4; // c = c / 4
console.log("After /= 4:", c);
c %= 3; // c = c % 3
console.log("After %= 3:", c);
c **= 2; // c = c ** 2
console.log("After **= 2:", c);
