//  Var

var x = 5;
console.log(x);
// we can reassign the value of x
x = 10;
console.log(x);

// Let

let y = 15;
console.log(y);
// we can reassign the value of y
y = 20;
console.log(y);
// but we cannot redeclare y in the same scope
// let y = 25; // This will throw an error

// Const

const z = 30;
console.log(z);
// we cannot reassign the value of z
// z = 35; // This will throw an error
// we cannot redeclare z in the same scope
// const z = 40; // This will also throw an error

